# Играта на Падок вече звучи като болид от 2026 🏁

Здравей!

Играта на Падок има ново обновление. Този път е за това как звучат болидите и как се изпреварва по правилата на сезон 2026.

## 🔊 Нов звук на двигателя

* **Изчислен, а не записан.** Звукът се смята в реално време от модел на двигателя: шестте цилиндъра, изпускателните тръби и турбината. Затова смяната на предавка, пукането при отпускане на газта и ревът на излизане от завоя звучат различно всеки път.
* **Като болидите от 2026.** V6 турбо хибрид: турбото набира със закъснение, а електромоторът MGU-K вие, когато дава мощност или зарежда. При спиране двигателят не заглъхва, защото зарежда батерията, точно както при истинските коли този сезон.
* **Истинските обороти.** Предавките се сменят около 11 900 об/мин, както при сегашните болиди. Оборотомерът показва същото.
* **Съперникът до теб.** Най-близкият бот вече е със собствен двигател. Чуваш как те настига, как сменя предавки и как профучава покрай теб.

## ⚡ Режим за изпреварване вместо DRS

Тази година DRS го няма. На негово място е режимът за изпреварване. Ако минеш линията до 1 секунда зад кола, получаваш допълнителна електрическа енергия за следващата обиколка. Играта я пуска сама, когато си на пълна газ по правата. На екрана виждаш „⚡ Изпреварване“ и колко енергия ти остава. Същото правило важи и за ботовете.

Правилата на състезанието се смениха, затова класацията „Състезание“ започва наново. Първите места на всяка писта са свободни.

