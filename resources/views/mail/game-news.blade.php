# Състезанието в Падок вече е истинско 🏁

Здравей!

Играта на Падок получи най-голямото си обновление досега. Досега в режим „Състезание“ задминаваше съперниците още на първия завой и оставаше сам на пистата. Вече не е така.

## 🏎️ Ботове, които се състезават

* **По-умни ботове.** Досега бяха бавни и пасивни. Вече карат с темпото на истински пилот, спират късно, защитават се и те атакуват, когато са плътно зад теб.
* **Грешки под натиск.** Притиснеш ли някого, той може да изпусне спирането и да се изнесе широко. Точно тогава е моментът за атака.
* **DRS зони.** На най-дългите прави, ако при засичането си до 1 секунда зад кола, крилото се отваря и получаваш допълнителна скорост за изпреварване.
* **Наказание при вина за удар.** Удариш ли някого отзад, получаваш +5 секунди, както при излизане от пистата. Ако те ударят, наказанието е за тях.
* **Истински финал.** След карирания флаг всички допътуват до края, а класирането показва разликите в секунди, наказанията и най-бързата обиколка.

## 📻 Като на телевизионния екран

* **Интервали в секунди** в кулата с позициите, вместо метри.
* **Радио съобщения:** кой те атакува, кога DRS е наличен, кой изпусна завоя, последна обиколка.
* **Радар за кола отстрани.** Когато някой е до теб, отстрани на екрана светва сигнал, за да не се удряте колело в колело.

## ⚔️ Битка с реални играчи

В класацията „Състезание“ натисни **„⚔️ Срещу“** до името на друг играч. Неговото най-добро състезание тръгва заедно с теб като полупрозрачна кола. Виждаш го в кулата, чуваш по радиото разликата на всяка обиколка и на финала разбираш кой е по-бърз. Не е нужно да сте онлайн по едно и също време.

## 🏆 Две класации

Класацията вече е разделена на две:

* **Сам на пистата** — чиста обиколка за атака на времето.
* **Състезание** — общото ти време за трите обиколки срещу ботовете, заедно с наказанията.

Досега времето от състезание изобщо не влизаше в класация, затова класацията „Състезание“ започва от нулата. Първите места на всяка писта са свободни.

Всяко време се проверява на сървъра, като цялото състезание се преиграва от записа на твоите команди. Измислено време не влиза в класацията.

