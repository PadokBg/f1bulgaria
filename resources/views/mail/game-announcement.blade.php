## 🎮 Как се кара

* **На компютър:** стрелки или WASD, C сменя камерата (гонитба или от кокпита), R рестартира. Ако имаш геймпад, включи го — играта го разпознава сама.
* **На телефон:** завърти екрана хоризонтално. Завиваш с бутони или като **накланяш телефона като волан**, газ и спирачка са под палците. Играта сама сваля графиката, за да върви гладко.

Съвет за първата обиколка: не гони време. Изкарай една спокойна, научи къде спираш и къде вече можеш да си на пълна газ, и тогава натисни. Доброто време идва с повторенията — а най-трудното обикновено е да спреш след „само още една“.

