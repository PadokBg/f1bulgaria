## 🏎️ Болид, който се държи като болид

Под капака е истинска симулация, не аркада: тежестта се премества при спиране и газ, гумите губят сцепление, ако прекалиш, колелата блокират при късно спиране, кербовете подхвърлят, чакълът наказва, а стената спира. Скоростите са автоматични, а на компютър можеш да ги сменяш и ръчно — избираш преди старта.

Хронометърът работи като на телевизионния тайминг: три сектора, лични рекорди и **лилави сектори** — най-бързите на всеки от тях поотделно, независимо от коя обиколка идват. След всяка обиколка сам на пистата получаваш и **анализ**: графика на скоростта по дистанция, спирачните зони, процент пълна газ и делтата спрямо духа, с който си карал.

## 🏁 Два режима

* **Сам на пистата.** Чиста обиколка за атака на времето. Само тя влиза в класацията — никой не ти се пречка.
* **Състезание.** Три обиколки срещу петима съперници. Стартираш от шеста позиция, чакаш петте светлини да угаснат и се биеш за място — с истински контакт между болидите.

## 👻 Духове, класация и седмично предизвикателство

На всяка писта кара **духът на Падок** — еталонна обиколка, която показва линията и точките за спиране. Настигнеш ли го, отключваш значка. После идва твоят собствен дух, а от класацията можеш да предизвикаш всеки друг играч на **дуел срещу неговата обиколка** — или да пратиш линк-покана на приятел.

Класацията е по писта, за цялата общност. Всяка записана обиколка се **преиграва на сървъра** от записа на твоите команди — измислено време не оцелява в класацията и лилавото си остава лилаво.

