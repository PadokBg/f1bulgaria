Здравей!

Дълго време Падок беше сайт, в който **гледаш** Формула 1 — календар, класирания, прогнози, новини. От днес можеш и да **караш**. Направихме 3D състезателен симулатор, който върви направо в браузъра — на компютър и на телефон, без инсталация, без сваляне, без регистрация за първата обиколка. Безплатен е и ще остане такъв.

