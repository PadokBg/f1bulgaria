<?php

declare(strict_types=1);

use App\Support\Ordinal;

it('пише поредното числително с българската наставка', function (int $number, string $expected) {
    expect(Ordinal::bg($number))->toBe($expected);
})->with([
    [1, '1-ви'],
    [2, '2-ри'],
    [3, '3-ти'],
    [4, '4-ти'],
    [5, '5-и'],
    [7, '7-ми'],
    [8, '8-ми'],
    [10, '10-и'],
    [11, '11-и'],
    [12, '12-и'],
    [17, '17-и'],
    [20, '20-и'],
    // С 22 коли на старта — „двадесет и първи", „двадесет и втори".
    [21, '21-ви'],
    [22, '22-ри'],
    [23, '23-ти'],
]);
